// Function to get current language from localStorage
function getCurrentLanguage() {
  const settings = JSON.parse(localStorage.getItem('appSettings') || '{}');
  return settings.language || 'bg';
}

// Function to translate text by key
function t(key, lang = null) {
  lang = lang || getCurrentLanguage();
  return translations[lang]?.[key] || translations.en[key] || key;
}

// Function to apply language to entire page
function applyLanguage(lang) {
  // Update all elements with data-i18n attribute
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    el.textContent = translations[lang]?.[key] || translations.en[key] || key;
  });
  
  // Update all placeholders with data-i18n-placeholder attribute
  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    const key = el.getAttribute('data-i18n-placeholder');
    el.placeholder = translations[lang]?.[key] || translations.en[key] || key;
  });
  
  // Update all titles with data-i18n-title attribute
  document.querySelectorAll('[data-i18n-title]').forEach(el => {
    const key = el.getAttribute('data-i18n-title');
    el.title = translations[lang]?.[key] || translations.en[key] || key;
  });
  
  // Update document language attribute
  document.documentElement.lang = lang;
  
  // Store current language
  const settings = JSON.parse(localStorage.getItem('appSettings') || '{}');
  settings.language = lang;
  localStorage.setItem('appSettings', JSON.stringify(settings));
}

// Initialize language on page load
document.addEventListener('DOMContentLoaded', function() {
  const lang = getCurrentLanguage();
  applyLanguage(lang);
});
